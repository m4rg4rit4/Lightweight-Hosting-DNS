const (
	zonesDir      = "/etc/bind/zones"
	autoZonesConf = "/etc/bind/autogenerated_zones.conf"
)

var (
	triggerChan = make(chan struct{}, 1)
	processMu   sync.Mutex
)

// TriggerSync signals the background engine to immediately process pending requests
// without waiting for the periodic ticker.
func TriggerSync() {
	select {
	case triggerChan <- struct{}{}:
	default:
	}
}

func runEngine(db *sql.DB) {
	ticker := time.NewTicker(60 * time.Second)
	defer ticker.Stop()

	// Run once immediately on start
	processRequests(db)

	for {
		select {
		case <-ticker.C:
			processRequests(db)
		case <-triggerChan:
			processRequests(db)
		}
	}
}

// maxRequestAttempts bounds the retries of a single request. Past it the row stays
// in 'error' for a human to look at, instead of spinning forever.
const maxRequestAttempts = 5

// requeueStalledRequests brings back work that would otherwise be lost forever: the
// main loop only ever selected 'pending', so a row left in 'processing' by a crash,
// or parked in 'error' by a transient named-checkconf failure, was never retried.
//
// Only recent rows are retried. The queue is a log going back months, and replaying
// old entries would rebuild zones from requests the current database state has long
// since superseded — on a node upgrading to this build, every historical failure
// would fire at once. Anything older than the window is stale by definition, and
// reconciling it is the panel's sync job, not a blind replay.
func requeueStalledRequests(db *sql.DB) {
	res, err := db.Exec(`
		UPDATE sys_dns_requests
		SET status = 'pending'
		WHERE status = 'processing'
		  AND attempts < ?
		  AND request_date > NOW() - INTERVAL 1 DAY
		  AND (started_at IS NULL OR started_at < NOW() - INTERVAL 10 MINUTE)`, maxRequestAttempts)
	if err != nil {
		log.Println("Error requeueing stalled requests:", err)
	} else if n, _ := res.RowsAffected(); n > 0 {
		log.Printf("Requeued %d stalled request(s)", n)
	}

	res, err = db.Exec(`
		UPDATE sys_dns_requests
		SET status = 'pending'
		WHERE status = 'error'
		  AND attempts < ?
		  AND request_date > NOW() - INTERVAL 1 DAY
		  AND (processed_date IS NULL OR processed_date < NOW() - INTERVAL 5 MINUTE)`, maxRequestAttempts)
	if err != nil {
		log.Println("Error requeueing failed requests:", err)
	} else if n, _ := res.RowsAffected(); n > 0 {
		log.Printf("Requeued %d failed request(s) for retry", n)
	}
}

func processRequests(db *sql.DB) {
	processMu.Lock()
	defer processMu.Unlock()

	requeueStalledRequests(db)

	rows, err := db.Query("SELECT id, action, domain, status FROM sys_dns_requests WHERE status = 'pending' ORDER BY id ASC")
	if err != nil {
		log.Println("Error fetching requests:", err)
		return
	}
	defer rows.Close()

	var requests []DNSRequest
	for rows.Next() {
		var req DNSRequest
		if err := rows.Scan(&req.ID, &req.Action, &req.Domain, &req.Status); err != nil {
			log.Println("Error scanning request:", err)
			continue
		}
		requests = append(requests, req)
	}

	if len(requests) == 0 {
		return
	}

	reloadNeeded := false
	newZonesAdded := false
	reloadedDomains := make(map[string]bool)
	var publicationIDs []int

	// Ensure dirs exist
	_ = os.MkdirAll(zonesDir, 0755)

	for _, req := range requests {
		db.Exec("UPDATE sys_dns_requests SET status = 'processing', started_at = NOW(), attempts = attempts + 1 WHERE id = ?", req.ID)

		zoneFilePath := fmt.Sprintf("%s/db.%s", zonesDir, req.Domain)

		if req.Action == "delete" {
			os.Remove(zoneFilePath)
			removeFromAutoConf(req.Domain)
			db.Exec("DELETE FROM sys_dns_zones WHERE domain = ?", req.Domain)
			publicationIDs = append(publicationIDs, req.ID)
			reloadNeeded = true
			newZonesAdded = true
		} else { // add or update
			var zoneID int
			err := db.QueryRow("SELECT id FROM sys_dns_zones WHERE domain = ?", req.Domain).Scan(&zoneID)
			if err != nil {
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", "Zone lookup failed: "+err.Error(), req.ID)
				continue
			}

			// Generate zone file with guaranteed increasing serial
			if err := ensureZoneEssentials(db, zoneID, req.Domain); err != nil {
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", err.Error(), req.ID)
				continue
			}
			oldSerialStr := readZoneSerial(zoneFilePath)
			serial := computeNextSerial(oldSerialStr)

			if err := generateZoneFile(db, zoneID, req.Domain, zoneFilePath, serial); err != nil {
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", err.Error(), req.ID)
				continue
			}
			addedToConf, confErr := addToAutoConf(req.Domain, zoneFilePath)
			if confErr != nil {
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", confErr.Error(), req.ID)
				continue
			}
			if addedToConf {
				newZonesAdded = true
			}

			// 1. Check zone syntax with named-checkzone
			cmdZone := exec.Command("named-checkzone", req.Domain, zoneFilePath)
			zoneOut, zoneErr := cmdZone.CombinedOutput()
			if zoneErr != nil {
				log.Printf("named-checkzone FAILED for %s:\n%s", req.Domain, string(zoneOut))
				if addedToConf {
					removeFromAutoConf(req.Domain)
				}
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", string(zoneOut), req.ID)
				continue
			}

			// 2. Check BIND configuration with named-checkconf
			cmdConf := exec.Command("named-checkconf", "/etc/bind/named.conf")
			confOut, confErr := cmdConf.CombinedOutput()
			if confErr != nil {
				log.Printf("named-checkconf FAILED:\n%s", string(confOut))
				if addedToConf {
					removeFromAutoConf(req.Domain)
				}
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", string(confOut), req.ID)
				continue
			}

			publicationIDs = append(publicationIDs, req.ID)
			reloadNeeded = true
			reloadedDomains[req.Domain] = true
		}
	}

	if reloadNeeded {
		err := reloadBind(newZonesAdded, reloadedDomains)
		for _, id := range publicationIDs {
			if err != nil {
				db.Exec("UPDATE sys_dns_requests SET status = 'error', error_log = ?, processed_date = NOW() WHERE id = ?", err.Error(), id)
			} else {
				db.Exec("UPDATE sys_dns_requests SET status = 'completed', error_log = NULL, processed_date = NOW() WHERE id = ?", id)
			}
		}
	}
}

var runBindCommand = func(name string, args ...string) ([]byte, error) {
	return exec.Command(name, args...).CombinedOutput()
}

// reloadBind applies changes to BIND9 using rndc with fallbacks to systemctl.
func reloadBind(newZonesAdded bool, domains map[string]bool) error {
	log.Println("Executing automatic reload of BIND...")

	// 1. If zones were added or removed from autogenerated_zones.conf, run rndc reconfig first
	if newZonesAdded {
		if out, err := runBindCommand("rndc", "reconfig"); err != nil {
			log.Printf("rndc reconfig warning: %v, output: %s", err, string(out))
		} else {
			log.Printf("rndc reconfig success: %s", strings.TrimSpace(string(out)))
		}
	}

	// 2. Reload specific modified zones with rndc reload <domain>
	for domain := range domains {
		if out, err := runBindCommand("rndc", "reload", domain); err != nil {
			log.Printf("rndc reload %s warning: %v, output: %s", domain, err, string(out))
		} else {
			log.Printf("rndc reload %s: %s", domain, strings.TrimSpace(string(out)))
		}
	}

	// 3. Global rndc reload
	out, err := runBindCommand("rndc", "reload")
	if err == nil {
		log.Printf("rndc reload successful: %s", strings.TrimSpace(string(out)))
		return nil
	}
	log.Printf("rndc reload failed (%v): %s. Falling back to systemctl reload...", err, string(out))

	// 4. Fallback to systemctl reload named
	if sysOut, sysErr := runBindCommand("systemctl", "reload", "named"); sysErr == nil {
		log.Println("systemctl reload named successful")
		return nil
	} else {
		log.Printf("systemctl reload named failed: %v (%s)", sysErr, string(sysOut))
	}

	// 5. Fallback to systemctl reload bind9
	if sysOut2, sysErr2 := runBindCommand("systemctl", "reload", "bind9"); sysErr2 == nil {
		log.Println("systemctl reload bind9 successful")
		return nil
	} else {
		log.Printf("systemctl reload bind9 failed: %v (%s)", sysErr2, string(sysOut2))
	}

	// 6. Last resort: systemctl restart named
	log.Println("Attempting systemctl restart named as last resort...")
	if rOut, rErr := runBindCommand("systemctl", "restart", "named"); rErr != nil {
		return fmt.Errorf("BIND publication failed: %v (%s)", rErr, string(rOut))
	} else {
		log.Println("systemctl restart named successful")
	}
	return nil
}

// soaSerialRe extracts the serial number from an SOA record (skipping mname and rname).
// Matches single-line and multi-line SOA formats, with or without parentheses.
var soaSerialRe = regexp.MustCompile(`(?i)\bSOA\b\s+\S+\s+\S+\s*(?:\(\s*)?(\d+)`)

// readZoneSerial extracts the serial from the SOA line of an existing zone file.
// Returns "" when the file is missing or has none.
func readZoneSerial(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	matches := soaSerialRe.FindStringSubmatch(string(b))
	if len(matches) > 1 {
		return matches[1]
	}
	return ""
}

// computeNextSerial calculates the next SOA serial (YYYYMMDDnn).
// It strictly guarantees that the new serial is greater than oldSerial and at least today's base.
func computeNextSerial(oldSerialStr string) string {
	todayPrefix := time.Now().Format("20060102")
	todayBase, _ := strconv.ParseInt(todayPrefix+"01", 10, 64)

	if oldSerialStr == "" {
		return fmt.Sprintf("%d", todayBase)
	}

	oldSerial, err := strconv.ParseInt(oldSerialStr, 10, 64)
	if err != nil || oldSerial < 1 {
		return fmt.Sprintf("%d", todayBase)
	}

	// If old serial is already today or greater, increment strictly so BIND is guaranteed to reload
	if oldSerial >= todayBase {
		return fmt.Sprintf("%d", oldSerial+1)
	}

	// Otherwise start fresh with today's base
	return fmt.Sprintf("%d", todayBase)
}

func generateZoneFile(db *sql.DB, zoneID int, domain, path, serial string) error {
	content, err := buildZoneFile(db, zoneID, domain, serial)
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0644)
}

// buildZoneFile renders the BIND9 zone file for a zone without touching disk, so the
// same output the engine writes can be served by /api-dns/zone/{domain}/export.
func buildZoneFile(db dnsDB, zoneID int, domain, serial string) (string, error) {
	rows, err := db.Query("SELECT name, type, content, ttl, priority FROM sys_dns_records WHERE zone_id = ? ORDER BY sort_order ASC, id ASC", zoneID)
	if err != nil {
		return "", err
	}
	defer rows.Close()

	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("; Autogenerated Zone for %s\n", domain))
	sb.WriteString(fmt.Sprintf("$ORIGIN %s.\n", domain))
	sb.WriteString("$TTL 3600\n\n")

	var records []DNSRecord
	for rows.Next() {
		var r DNSRecord
		if err := rows.Scan(&r.Name, &r.Type, &r.Content, &r.TTL, &r.Priority); err != nil {
			return "", err
		}
		records = append(records, r)
	}

	if err := rows.Err(); err != nil {
		return "", err
	}

	// SOA handling
	hasSOA := false
	for _, r := range records {
		if r.Type == "SOA" {
			soaContent := soaWithSerial(r.Content, serial)
			sb.WriteString(fmt.Sprintf("@\tIN\tSOA\t%s\n", soaContent))
			hasSOA = true
			break
		}
	}
	if !hasSOA {
		var ns []string
		for _, record := range records {
			if record.Type == "NS" {
				ns = append(ns, record.Content)
			}
		}
		nameservers, err := resolveNameservers(ns)
		if err != nil {
			return "", err
		}
		sb.WriteString(fmt.Sprintf("@\tIN\tSOA\t%s hostmaster.%s. ( %s 3600 1800 604800 86400 )\n", nameservers[0], domain, serial))
	}

	// Other records
	for _, r := range records {
		if r.Type == "SOA" {
			continue
		}
		prio := ""
		if (r.Type == "MX" || r.Type == "SRV") && r.Priority.Valid {
			prio = fmt.Sprintf("%d\t", r.Priority.Int32)
		}

		content := r.Content
		if r.Type == "TXT" {
			// Remove any existing quotes to normalize
			content = strings.TrimSpace(content)
			if strings.HasPrefix(content, "\"") && strings.HasSuffix(content, "\"") {
				content = content[1 : len(content)-1]
			}

			// Split into 255-byte chunks
			var chunks []string
			for len(content) > 0 {
				chunkSize := 255
				if len(content) < 255 {
					chunkSize = len(content)
				}
				chunks = append(chunks, "\""+content[:chunkSize]+"\"")
				content = content[chunkSize:]
			}
			content = strings.Join(chunks, " ")
		}

		sb.WriteString(fmt.Sprintf("%s\t%d\tIN\t%s\t%s%s\n", r.Name, r.TTL, r.Type, prio, content))
	}

	return sb.String(), nil
}

// addToAutoConf reports whether it actually appended a new zone block, so the caller
// can undo exactly what it added if named-checkconf then rejects the config.
func addToAutoConf(domain, path string) (bool, error) {
	b, err := os.ReadFile(autoZonesConf)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	content := string(b)
	target := fmt.Sprintf("zone \"%s\"", domain)
	if strings.Contains(content, target) {
		return false, nil
	}
	appendStr := fmt.Sprintf("zone \"%s\" {\n\ttype master;\n\tfile \"%s\";\n};\n", domain, path)
	f, err := os.OpenFile(autoZonesConf, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return false, err
	}
	if _, err = f.WriteString(appendStr); err != nil {
		f.Close()
		return false, err
	}
	if err = f.Close(); err != nil {
		return false, err
	}
	return true, nil
}

func removeFromAutoConf(domain string) {
	// Simplistic remove (in a real scenario, use regex or proper parsing)
	b, _ := os.ReadFile(autoZonesConf)
	content := string(b)
	targetStart := fmt.Sprintf("zone \"%s\" {", domain)
	idx := strings.Index(content, targetStart)
	if idx != -1 {
		endIdx := strings.Index(content[idx:], "};")
		if endIdx != -1 {
			newContent := content[:idx] + content[idx+endIdx+2:]
			// clean up trailing newlines if any
			os.WriteFile(autoZonesConf, []byte(newContent), 0644)
		}
	}
}
